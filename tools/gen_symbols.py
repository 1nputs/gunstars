#!/usr/bin/env python3
"""Write src/symbols_gen.h from the disassembly (build/disasm/routines.json, symbols.json) and
tools/disasm/names.txt: SYM_<name> for every routine and named ROM address, v_<name> for named
work RAM (the offset), and the tables the tests print names from.

usage: gen_symbols.py [--out src/symbols_gen.h]
"""
import argparse, json, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'src', 'symbols_gen.h'))
    a = ap.parse_args()
    routines = json.load(open(os.path.join(ROOT, 'build', 'disasm', 'routines.json')))
    names = {}
    for line in open(os.path.join(ROOT, 'tools', 'disasm', 'names.txt')):
        f = line.split('#', 1)[0].split()
        if len(f) >= 2:
            names[int(f[0], 16)] = f[1].lstrip('.')     # '.': an inner label
    rom = {}
    for n, r in routines.items():
        rom[r['addr']] = n
    for ad, n in names.items():
        if ad < 0x100000:
            rom[ad] = n
    ramv = {ad & 0xFFFF: n for ad, n in names.items() if ad >= 0xFF0000}
    trivial = sorted(r['addr'] for r in routines.values() if r['insns'] == 1)
    out = ['/* Generated by tools/gen_symbols.py from the disassembly and tools/disasm/names.txt: do not edit. */',
           '#pragma once', '#include <stdint.h>', '']
    out.append('/* ROM: routines and named addresses */')
    for ad in sorted(rom):
        out.append(f'#define SYM_{rom[ad]} 0x{ad:06X}u')
    out.append('')
    out.append('/* work RAM: offsets ($FFxxxx & $FFFF) */')
    out.append('enum {')
    for ad in sorted(ramv):
        out.append(f'    {ramv[ad]} = 0x{ad:04X},')
    out.append('};')
    out.append('')
    out.append('struct sym { uint32_t addr; const char *name; };')
    out.append('static const struct sym rom_syms[] = {')
    for ad in sorted(rom):
        out.append(f'    {{ 0x{ad:06X}u, "{rom[ad]}" }},')
    out.append('};')
    out.append('static const struct sym ram_syms[] = {')
    for ad in sorted(ramv):
        out.append(f'    {{ 0x{ad:04X}u, "{ramv[ad]}" }},')
    out.append('};')
    out.append('/* routines of one instruction (a shared rts, a jump): their recorded calls need no port */')
    out.append('static const uint32_t trivial_syms[] = {')
    for i in range(0, len(trivial), 8):
        out.append('    ' + ', '.join(f'0x{t:06X}u' for t in trivial[i:i + 8]) + ',')
    out.append('};')
    open(a.out, 'w').write('\n'.join(out) + '\n')
    print(f'{a.out}: {len(rom)} ROM symbols, {len(ramv)} RAM names, {len(trivial)} trivial routines')


if __name__ == '__main__':
    main()
